import { chromium } from 'playwright';
import fs from 'fs';
const OUT='/Users/eyoel/vibecoding/job/websites-portfolio/media';
const b=await chromium.launch({channel:'chrome',headless:true});
const dir='raw/jobportal';fs.rmSync(dir,{recursive:true,force:true});
const c=await b.newContext({viewport:{width:1440,height:900},recordVideo:{dir,size:{width:1440,height:900}}});
const tc=Date.now();
const p=await c.newPage();const w=ms=>p.waitForTimeout(ms);
const base='http://localhost:8000';
const shot=n=>p.screenshot({path:`${OUT}/${n}.png`});
const smooth=async(to,ms)=>{const y0=await p.evaluate(()=>scrollY);const n=ms/40;for(let i=1;i<=n;i++){const t=i/n,e=t<.5?2*t*t:1-Math.pow(-2*t+2,2)/2;await p.evaluate(y=>scrollTo(0,y),y0+(to-y0)*e);await w(40)}};
await p.goto(base+'/jobs?max_age=3',{waitUntil:'load'});await w(1500);
const startSec=(Date.now()-tc)/1000;
await shot('jobportal-1');
await smooth(500,1800);await w(400);await smooth(0,800);
const href=await p.evaluate(()=>{const a=[...document.querySelectorAll('a')].find(a=>/^\/jobs\/[^?]+/.test(a.getAttribute('href')||'')&&!/review-posters|cv-status|draft-status/.test(a.getAttribute('href')));return a&&a.getAttribute('href')});
console.log('detail',href);
await p.goto(base+href,{waitUntil:'load'});await w(1500);await shot('jobportal-2');
await smooth(700,1800);await w(500);
await p.goto(base+'/gap-report',{waitUntil:'load'});await w(1200);await shot('jobportal-3');
await smooth(600,1800);await w(400);
await p.goto(base+'/learn',{waitUntil:'load'});await w(1500);await shot('jobportal-4');
await smooth(400,1500);await w(500);
fs.writeFileSync('raw/jobportal/start.txt',String(startSec));
const vp=await p.video().path();
await c.close();await b.close();
fs.renameSync(vp,'raw/jobportal/raw.webm');
